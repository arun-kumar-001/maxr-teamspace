#!/usr/bin/env bash
set -euo pipefail

echo "========================================="
echo "   MAXR Teamspace Server Deployment      "
echo "========================================="

# 1. Resolve repository root
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"
echo "[1/6] Repository directory: $REPO_ROOT"

# 2. Check and configure deploy/.env.production
ENV_FILE="$REPO_ROOT/deploy/.env.production"
ROOT_ENV="$REPO_ROOT/.env.production"
CERT_DIR="$REPO_ROOT/deploy/certs"

if [ ! -f "$ENV_FILE" ]; then
  echo "[2/6] deploy/.env.production not found. Generating default production configuration..."
  
  DB_PASS=$(openssl rand -hex 16 2>/dev/null || date +%s | sha256sum | head -c 32)
  REDIS_PASS=$(openssl rand -hex 16 2>/dev/null || date +%s | sha256sum | head -c 32)
  SESSION_SEC=$(openssl rand -hex 32 2>/dev/null || date +%s | sha256sum | head -c 64)
  STORAGE_SEC=$(openssl rand -hex 32 2>/dev/null || date +%s | sha256sum | head -c 64)
  
  mkdir -p "$CERT_DIR"
  
  cat <<EOF > "$ENV_FILE"
# Auto-generated by deploy/server-deploy.sh
DB_USER=maxr
DB_NAME=maxr_teamspace
DB_PASSWORD=${DB_PASS}
REDIS_PASSWORD=${REDIS_PASS}

HTTP_PORT=80
HTTPS_PORT=443
TLS_CERT_DIR=${CERT_DIR}

SESSION_SECRET=${SESSION_SEC}
STORAGE_SIGNING_SECRET=${STORAGE_SEC}
CORS_ORIGIN=https://localhost
APP_URL=https://localhost
LOG_LEVEL=info

EMAIL_DRIVER=smtp
EMAIL_FROM=no-reply@maxr.internal
SMTP_HOST=localhost
SMTP_PORT=1025

STORAGE_DRIVER=local
STORAGE_REQUIRE_SCAN=false
EOF
  chmod 600 "$ENV_FILE"
  echo "      Generated $ENV_FILE with secure credentials."
else
  echo "[2/6] Found existing $ENV_FILE"
  # Ensure mandatory keys are present and not empty
  if ! grep -q "^SESSION_SECRET=" "$ENV_FILE" || grep -q "^SESSION_SECRET=$" "$ENV_FILE"; then
    SESSION_SEC=$(openssl rand -hex 32 2>/dev/null || date +%s | sha256sum | head -c 64)
    sed -i "s/^SESSION_SECRET=.*/SESSION_SECRET=${SESSION_SEC}/" "$ENV_FILE" || echo "SESSION_SECRET=${SESSION_SEC}" >> "$ENV_FILE"
  fi
  if ! grep -q "^STORAGE_SIGNING_SECRET=" "$ENV_FILE" || grep -q "^STORAGE_SIGNING_SECRET=$" "$ENV_FILE"; then
    STORAGE_SEC=$(openssl rand -hex 32 2>/dev/null || date +%s | sha256sum | head -c 64)
    sed -i "s/^STORAGE_SIGNING_SECRET=.*/STORAGE_SIGNING_SECRET=${STORAGE_SEC}/" "$ENV_FILE" || echo "STORAGE_SIGNING_SECRET=${STORAGE_SEC}" >> "$ENV_FILE"
  fi
  if ! grep -q "^CORS_ORIGIN=" "$ENV_FILE" || grep -q "^CORS_ORIGIN=$" "$ENV_FILE"; then
    echo "CORS_ORIGIN=https://localhost" >> "$ENV_FILE"
  fi
  if ! grep -q "^APP_URL=" "$ENV_FILE" || grep -q "^APP_URL=$" "$ENV_FILE"; then
    echo "APP_URL=https://localhost" >> "$ENV_FILE"
  fi
  if ! grep -q "^STORAGE_REQUIRE_SCAN=" "$ENV_FILE"; then
    echo "STORAGE_REQUIRE_SCAN=false" >> "$ENV_FILE"
  fi
fi

# Mirror to root .env.production as well
cp -f "$ENV_FILE" "$ROOT_ENV"
chmod 600 "$ROOT_ENV"

# 3. Ensure TLS certificates exist
TLS_DIR=$(grep -E '^TLS_CERT_DIR=' "$ENV_FILE" | cut -d '=' -f2- | tr -d '"' | tr -d "'" || echo "")
TLS_DIR="${TLS_DIR:-$CERT_DIR}"

if [ ! -f "$TLS_DIR/fullchain.pem" ] || [ ! -f "$TLS_DIR/privkey.pem" ]; then
  echo "[3/6] TLS certificates not found in $TLS_DIR. Generating self-signed SSL certificates..."
  mkdir -p "$TLS_DIR"
  openssl req -x509 -nodes -days 365 -newkey rsa:2048 \
    -keyout "$TLS_DIR/privkey.pem" \
    -out "$TLS_DIR/fullchain.pem" \
    -subj "/CN=localhost" 2>/dev/null || true
  chmod 600 "$TLS_DIR/privkey.pem" 2>/dev/null || true
  chmod 644 "$TLS_DIR/fullchain.pem" 2>/dev/null || true
  echo "      SSL certificates created in $TLS_DIR"
else
  echo "[3/6] TLS certificates found in $TLS_DIR"
fi

# 4. Start PostgreSQL and Redis
echo "[4/6] Starting PostgreSQL and Redis containers..."
docker compose -f deploy/docker-compose.prod.yml --env-file "$ENV_FILE" up -d postgres redis

echo "      Waiting for PostgreSQL to accept connections..."
for i in {1..30}; do
  if docker compose -f deploy/docker-compose.prod.yml --env-file "$ENV_FILE" exec -T postgres pg_isready -U maxr -d maxr_teamspace >/dev/null 2>&1; then
    echo "      PostgreSQL is ready!"
    break
  fi
  sleep 1
done

# 5. Run Database Migrations
echo "[5/6] Running database migrations..."
docker compose -f deploy/docker-compose.prod.yml --env-file "$ENV_FILE" run --rm migrate

# 6. Build and start full stack (API & Web)
echo "[6/6] Building and starting all containers (Web & API)..."
if ! docker compose -f deploy/docker-compose.prod.yml --env-file "$ENV_FILE" up -d --build; then
  echo "========================================="
  echo "Container start failed! Dumping API logs:"
  echo "========================================="
  docker compose -f deploy/docker-compose.prod.yml --env-file "$ENV_FILE" logs --tail 50 api || true
  exit 1
fi

echo "========================================="
echo "   Deployment completed successfully!    "
echo "========================================="
docker compose -f deploy/docker-compose.prod.yml --env-file "$ENV_FILE" ps
